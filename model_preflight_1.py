"""Offline preflight: verify registered SHA-256 then load trusted local model.

ONLY run on models generated by your own training pipeline. joblib uses pickle
and loading untrusted files can execute arbitrary code. Never run on Pi here.
"""
import argparse
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd

from model_release_1 import get_checked, store

EXPECTED_FEATURES = [
    "ear", "mar", "blink", "blink_rate_10s",
    "nod_ratio", "head_ratio", "head_motion",
]


def check(registry, version):
    path, record = get_checked(store(registry), version)
    report = json.loads((path / "validation.json").read_text(encoding="utf-8"))
    if not report.get("passed_initial_gate"):
        raise ValueError("Validation report did not pass gate")
    if report.get("features") != EXPECTED_FEATURES:
        raise ValueError("Validation feature schema/order mismatch")
    if record.get("synthetic_test_only") is not True:
        raise ValueError("This test preflight accepts synthetic test versions only")
    # Only after hash verification; never load files from untrusted sources.
    payload = joblib.load(path / "model.joblib")
    if not isinstance(payload, dict):
        raise ValueError("Model payload must be a dict")
    if payload.get("features") != EXPECTED_FEATURES:
        raise ValueError("Model feature schema/order mismatch")
    if payload.get("labels") != [0, 1]:
        raise ValueError("Model labels must be [0,1]")
    model = payload.get("model")
    if not callable(getattr(model, "predict", None)):
        raise ValueError("Model has no predict()")
    classes = getattr(model, "classes_", None)
    if classes is None or list(classes) != [0, 1]:
        raise ValueError("Trained model classes must be [0,1]")
    samples = pd.DataFrame([
        [0.30, 0.18, 0, 3.0, 0.06, 0.50, 0.01],
        [0.17, 0.62, 2, 7.0, 0.38, 0.70, 0.12],
    ], columns=EXPECTED_FEATURES)
    pred = np.asarray(model.predict(samples))
    if pred.shape != (2,) or not set(pred.tolist()).issubset({0, 1}):
        raise ValueError("Prediction output shape/labels invalid")
    return {
        "preflight_passed": True,
        "simulation_only": True,
        "version": version,
        "sha256_model": record["model_sha256"],
        "sha256_report": record["report_sha256"],
        "feature_count": len(EXPECTED_FEATURES),
        "labels": [0, 1],
        "smoke_test_predictions": pred.tolist(),
        "note": "Local test only; Pi runtime compatibility and real-data performance NOT verified",
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--registry", default="model_registry_test")
    p.add_argument("--version", required=True)
    args = p.parse_args()
    try:
        print(json.dumps(check(args.registry, args.version), ensure_ascii=False, indent=2))
    except (ValueError, KeyError, OSError, ImportError, AttributeError, TypeError) as exc:
        p.exit(1, f"Preflight stopped safely: {exc}\n")


if __name__ == "__main__":
    main()
